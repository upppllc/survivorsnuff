// Preview: node --env-file=.env scripts/import-season-51.mjs
// Import:  node --env-file=.env scripts/import-season-51.mjs --write
// Additive only: existing rows are never edited or removed.
import { season, castaways, episodes } from "../src/lib/data/season-51.js"

const write = process.argv.includes("--write")
const token = process.env.CONTIBASE_ACCESS_TOKEN
if (!token) throw new Error("CONTIBASE_ACCESS_TOKEN is required")

const definitions = [
  ["seasons", "CONTIBASE_SEASONS_TABLE_ID", [season], (row) => String(row.season_number)],
  ["castaways", "CONTIBASE_CASTAWAYS_TABLE_ID", castaways, (row) => row.name],
  ["episodes", "CONTIBASE_EPISODES_TABLE_ID", episodes, (row) => String(row.episode_number)],
]
const headers = { authorization: `Bearer ${token}`, "content-type": "application/json" }
const query = new URLSearchParams({
  filters: JSON.stringify({ field: "season_number", operator: "eq", value: 51 }),
  limit: "1000",
})

async function request(url, options = {}) {
  const response = await fetch(url, { headers, signal: AbortSignal.timeout(30_000), ...options })
  if (!response.ok) throw new Error(`Contibase request failed (${response.status}); no further rows will be written`)
  return response.json()
}

// Validate all tables before writing the first row.
const plans = []
for (const [label, envName, rows, identity] of definitions) {
  const tableId = process.env[envName]
  if (!tableId) throw new Error(`${envName} is required`)
  const url = `https://www.contibase.com/api/v1/tables/${encodeURIComponent(tableId)}`
  const table = await request(`${url}?${query}`)
  if (!Array.isArray(table.rows) || !table.columns?.season_number) throw new Error(`Unexpected ${label} schema`)
  if (table.rows.some((row) => row.season_number !== 51)) throw new Error(`Season filter failed for ${label}`)
  if (table.total_rows > table.rows.length) throw new Error(`Incomplete ${label} response; refusing to import`)
  const seen = new Set()
  for (const row of table.rows) {
    const key = identity(row)
    if (seen.has(key)) throw new Error(`Duplicate ${label} identity: ${key}`)
    seen.add(key)
  }
  const missing = rows.filter((row) => !seen.has(identity(row)))
  console.log(`${label}: ${table.rows.length} existing; ${missing.length} to add`)
  plans.push({ label, url, columns: table.columns, missing, identity })
}

if (!write) {
  console.log("Preview complete. Use --write to add the missing season 51 records.")
} else {
  for (const plan of plans) {
    for (const row of plan.missing) {
      // The live database generates IDs. Local photos/source metadata stay in the
      // checked-in data module because the current table has no image columns.
      const row_data = Object.fromEntries(
        Object.entries(row).filter(([key]) => plan.columns[key]?.is_db_column && !plan.columns[key]?.is_autogenerated)
      )
      await request(`${plan.url}/rows`, { method: "POST", body: JSON.stringify({ row_data }) })
      console.log(`Added ${plan.label}: ${plan.identity(row)}`)
    }
    const verified = await request(`${plan.url}?${query}`)
    for (const row of plan.missing) {
      const matches = verified.rows.filter((item) => plan.identity(item) === plan.identity(row))
      if (matches.length !== 1) throw new Error(`Could not verify ${plan.label}: ${plan.identity(row)}`)
    }
  }
  console.log("Season 51 import verified. Existing records were preserved.")
}
